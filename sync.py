"""Write the general working rules, and their check, into a project.

    python3 ../working-rules/sync.py .            # from inside one project
    python3 sync.py ../golden-path ../xcape       # several at once
    python3 sync.py                               # every sibling that already has a copy

Two files are written into each project, both generated and never edited there:

    .claude/rules/general.md        the rules, under a header recording their hash
    scripts/lint-working-rules.py   check.py, which fails when the copy was edited

Nothing is committed: review the diff in each project and commit it there.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
COPY = Path(".claude/rules/general.md")
CHECK = Path("scripts/lint-working-rules.py")
MARKER = "<!-- working-rules-sha256: "

HEADER = (
    "<!-- Copyright (c) 2025–2026 Athena Decision Systems SAS. All rights reserved. -->\n"
    "<!-- GENERATED — do not edit this file. It is a copy of general.md in the working-rules\n"
    "     repository. Change the rules there, then run `python3 ../working-rules/sync.py .`\n"
    "     in each project. scripts/lint-working-rules.py fails if this copy is edited in place. -->\n"
)


def write_if_changed(path: Path, data: bytes) -> bool:
    if path.is_file() and path.read_bytes() == data:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return True


def sync(project: Path, body: bytes, check: bytes) -> None:
    if not (project / ".git").exists():
        print(f"{project}: not a git repository — skipped")
        return
    digest = hashlib.sha256(body).hexdigest()
    copy = HEADER.encode("utf-8") + f"{MARKER}{digest} -->\n".encode("utf-8") + body
    changed = [
        str(rel)
        for rel, data in ((COPY, copy), (CHECK, check))
        if write_if_changed(project / rel, data)
    ]
    print(f"{project.name}: " + (", ".join(changed) + " updated" if changed else "already up to date"))


def main(argv: list[str]) -> int:
    body = (HERE / "general.md").read_bytes()
    check = (HERE / "check.py").read_bytes()
    if argv:
        projects = [Path(a).resolve() for a in argv]
    else:
        projects = sorted(p for p in HERE.parent.iterdir() if (p / COPY).is_file())
        if not projects:
            print("No project beside working-rules has a copy yet. Name the projects to install into.")
            return 1
    for project in projects:
        if project == HERE:
            continue
        sync(project, body, check)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
